// File checks (pure). Never trust the browser's file name or MIME type: look at the bytes.

export const MAX_IMAGE_BYTES = 1024 * 1024; // logos and signatures

export type ImageType = { ext: "png" | "jpg"; contentType: "image/png" | "image/jpeg" };

/** PNG or JPEG by magic number, else null. (SVG is refused on purpose: it can carry scripts.) */
export function sniffImage(buf: Uint8Array): ImageType | null {
  if (buf.length >= 8 && buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47 && buf[4] === 0x0d && buf[5] === 0x0a && buf[6] === 0x1a && buf[7] === 0x0a) {
    return { ext: "png", contentType: "image/png" };
  }
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) {
    return { ext: "jpg", contentType: "image/jpeg" };
  }
  return null;
}

/**
 * Width and height from the PNG IHDR chunk or the JPEG start-of-frame marker, without decoding.
 * A small file can declare a huge image ("decompression bomb"); null when it cannot be read.
 */
export function imageSize(buf: Uint8Array): { width: number; height: number } | null {
  const type = sniffImage(buf);
  if (!type) return null;
  const u16 = (i: number) => (buf[i] << 8) | buf[i + 1];
  const u32 = (i: number) => ((buf[i] << 24) >>> 0) + (buf[i + 1] << 16) + (buf[i + 2] << 8) + buf[i + 3];
  if (type.ext === "png") {
    // signature (8) + chunk length (4) + "IHDR" (4) + width (4) + height (4)
    if (buf.length < 24 || buf[12] !== 0x49 || buf[13] !== 0x48 || buf[14] !== 0x44 || buf[15] !== 0x52) return null;
    return { width: u32(16), height: u32(20) };
  }
  let i = 2;
  while (i + 9 < buf.length) {
    if (buf[i] !== 0xff) return null;
    const marker = buf[i + 1];
    if (marker === 0xff) { i++; continue; } // fill byte
    if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) { i += 2; continue; } // no length
    const isSof = marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc;
    if (isSof) return { height: u16(i + 5), width: u16(i + 7) };
    if (marker === 0xd9 || marker === 0xda) return null; // end / start of scan before any frame header
    i += 2 + u16(i + 2);
  }
  return null;
}

export const MAX_IMAGE_SIDE = 4000;
export const MAX_IMAGE_PIXELS = 12_000_000;

export function imageSizeAcceptable(size: { width: number; height: number } | null): boolean {
  if (!size || size.width < 1 || size.height < 1) return false;
  return size.width <= MAX_IMAGE_SIDE && size.height <= MAX_IMAGE_SIDE && size.width * size.height <= MAX_IMAGE_PIXELS;
}

export function isPdf(buf: Uint8Array): boolean {
  return buf.length >= 5 && buf[0] === 0x25 && buf[1] === 0x50 && buf[2] === 0x44 && buf[3] === 0x46 && buf[4] === 0x2d; // %PDF-
}

/**
 * Storage keys are generated by the server ("logos/<id>-<random>.png"). Anything else — "..",
 * backslashes, absolute paths, odd characters — is rejected so a key can never leave the store.
 */
export function isSafeStorageKey(key: string): boolean {
  return /^[a-z]+(\/[A-Za-z0-9_-]+)*\/[A-Za-z0-9_-]+\.(png|jpg|pdf|json)$/.test(key) && key.length <= 200;
}

/** "QT-BKK-2611-0001-R1" → a safe download file name. */
export function pdfFileName(displayNumber: string, suffix = ""): string {
  return `${displayNumber.replace(/[^A-Za-z0-9-]/g, "_")}${suffix}.pdf`;
}

export const MAX_PO_BYTES = 10 * 1024 * 1024; // the customer's purchase order (PDF or a photo)

export type PoFileType = { ext: "pdf" | "png" | "jpg"; contentType: "application/pdf" | "image/png" | "image/jpeg" };

/** A PO file is a PDF, PNG or JPEG by its bytes. */
export function sniffPoFile(buf: Uint8Array): PoFileType | null {
  if (isPdf(buf)) return { ext: "pdf", contentType: "application/pdf" };
  return sniffImage(buf);
}
